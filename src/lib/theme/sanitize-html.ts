import sanitizeHtml from "sanitize-html";

const ALLOWED_TAGS = [
  "div",
  "span",
  "section",
  "header",
  "footer",
  "main",
  "nav",
  "aside",
  "article",
  "ul",
  "ol",
  "li",
  "a",
  "img",
  "h1",
  "h2",
  "h3",
  "h4",
  "h5",
  "h6",
  "strong",
  "em",
  "small",
  "table",
  "thead",
  "tbody",
  "tr",
  "td",
  "th",
  "p",
  "br",
];

const ALLOWED_ATTRIBUTES: Record<string, string[]> = {
  "*": ["class", "id", "title"],
  a: ["href", "target", "rel"],
  img: ["src", "alt", "width", "height", "loading", "referrerpolicy"],
  td: ["colspan", "rowspan"],
  th: ["colspan", "rowspan", "scope"],
  // Hooks generated by `placeholders.ts` that user CSS targets.
  section: ["data-status", "data-domain"],
  tr: ["data-type", "data-index"],
};

const RELATIVE_URL_BASE = "https://listae.invalid";

/** Browsers strip these before resolving a URL attribute (WHATWG URL). */
function normalizeUrlAttribute(value: string): string {
  let start = 0;
  let end = value.length;
  while (start < end && value.charCodeAt(start) <= 0x20) start++;
  while (end > start && value.charCodeAt(end - 1) <= 0x20) end--;
  return value.slice(start, end).replace(/[\t\n\r]/g, "");
}

/**
 * Only `https:` URLs and root-relative paths (`/…`, never `//` or `/\`).
 * Runs on the decoded value, after placeholders were substituted, so a
 * scheme assembled from pieces (`java{{x}}script:`) is judged as a whole.
 */
export function safeThemeUrl(value: string): string | null {
  const url = normalizeUrlAttribute(value);

  // The value is kept as written once it resolves the way we allow. A
  // path-absolute URL keeps the page origin whatever the base host is, so
  // `/\evil.example` (which browsers read as `//evil.example`) is refused.
  try {
    if (url.startsWith("/")) {
      return new URL(url, RELATIVE_URL_BASE).origin === RELATIVE_URL_BASE
        ? url
        : null;
    }

    const parsed = new URL(url);
    return parsed.protocol === "https:" && parsed.hostname ? url : null;
  } catch {
    return null;
  }
}

function withSafeUrl(
  attribs: sanitizeHtml.Attributes,
  name: "href" | "src",
): sanitizeHtml.Attributes {
  const next = { ...attribs };
  if (name in next) {
    const safe = safeThemeUrl(next[name]!);
    if (safe === null) {
      delete next[name];
    } else {
      next[name] = safe;
    }
  }
  return next;
}

/** Sets `name` last, so it serializes after the author's attributes. */
function forceAttribute(
  attribs: sanitizeHtml.Attributes,
  name: string,
  value: string,
): sanitizeHtml.Attributes {
  const next = { ...attribs };
  delete next[name];
  next[name] = value;
  return next;
}

const TEMPLATE_MARKUP_OPTIONS: sanitizeHtml.IOptions = {
  allowedTags: ALLOWED_TAGS,
  allowedAttributes: ALLOWED_ATTRIBUTES,
  allowedSchemes: ["https"],
  allowProtocolRelative: false,
};

const FINAL_DOCUMENT_OPTIONS: sanitizeHtml.IOptions = {
  ...TEMPLATE_MARKUP_OPTIONS,
  transformTags: {
    a: (tagName, attribs) => ({
      tagName,
      attribs: forceAttribute(
        withSafeUrl(attribs, "href"),
        "rel",
        "noopener noreferrer",
      ),
    }),
    img: (tagName, attribs) => ({
      tagName,
      attribs: forceAttribute(
        withSafeUrl(attribs, "src"),
        "referrerpolicy",
        "no-referrer",
      ),
    }),
  },
};

/**
 * Runs on the **final** profile document (template with placeholders
 * already substituted) on every render and in the editor preview, and on
 * the template before it is stored.
 */
export function sanitizeThemeHtml(html: string): string {
  return sanitizeHtml(html, FINAL_DOCUMENT_OPTIONS);
}

/**
 * Same tag and attribute allowlist, without the URL post-filter. Only used
 * at save time to see which attributes of the author's template would keep
 * a `{{placeholder}}` (`sanitizeThemeHtml` drops `href="{{username}}"`, so
 * it would never be reported). Never render its output.
 */
export function sanitizeThemeTemplateMarkup(html: string): string {
  return sanitizeHtml(html, TEMPLATE_MARKUP_OPTIONS);
}
